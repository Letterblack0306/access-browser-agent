'use strict';

const assert = require('node:assert/strict');
const childProcess = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');

const main = read('electron/main.js');
const preload = read('electron/preload.js');
const renderer = read('electron/renderer.js');
const html = read('electron/index.html');
const viewState = read('electron/runtime-view-state.js');
childProcess.execFileSync(process.execPath, ['--check', path.join(root, 'electron', 'agent-workflow-view.js')]);

assert.match(main, /ide:runtime-stop/u);
assert.match(main, /ide:runtime-restart/u);
assert.match(main, /stopOwnedRuntime/u);
assert.match(main, /runtimeControl: \{ active: runtimeActive \}/u, 'Runtime lifecycle state must be distinct from active task execution.');
assert.match(main, /restartOwnedRuntime/u);
assert.match(main, /createConfiguredAgentRuntime/u, 'Persisted provider settings must be applied when Electron starts and when workspaces change.');
assert.match(main, /await runtime\.updateProviderSettings\(preferenceValues\)/u, 'Runtime start must validate the saved provider before reporting provider state.');
assert.match(main, /await runtime\.resetForFreshRuntime\(\)/u, 'Every configured runtime must clear its prior current-session pointer.');
assert.match(main, /ManagedChrome/u);
assert.match(preload, /runtimeStop/u);
assert.match(preload, /runtimeRestart/u);
assert.match(preload, /browserStart/u);
assert.doesNotMatch(html, /id="agentControl"/u);
assert.match(renderer, /id="liveAgentControl"/u);
assert.match(renderer, /Start Runtime/u);
assert.match(renderer, /Stop Runtime/u);
assert.match(renderer, /USER TERMINAL/u);
assert.match(renderer, /renderBrowserWorkflowState/u);
assert.match(renderer, /const relay = result\.relay \|\| result; const running = relay\.running === true/u, 'Relay UI must read the authority response from its relay field.');
assert.match(renderer, /Opening browser, checking tabs, and starting relay/u, 'Start Relay must run the complete browser setup loop.');
assert.match(main, /browserProviderTarget: result\.selectedTarget \|\| result\.relay\?\.target \|\| null/u, 'The chosen browser page must persist for future relay starts.');
assert.match(renderer, /browserWorkflow/u);
assert.match(renderer, /data-step="instruction"/u);
assert.match(renderer, /RuntimeViewState/u);
assert.match(viewState, /fromSnapshot/u);
assert.match(viewState, /withRelayFeedback/u);
assert.match(html, /id="footerRuntime"/u);
assert.match(html, /id="footerWorkspace"/u);
assert.doesNotMatch(html, /footerBrowser|agent-owned-browser-controls/u);
assert.match(renderer, /refreshRuntimeControlStatus/u);
assert.doesNotMatch(renderer, /ui\.browserCdpPort\.value/u, 'Renderer must not bind a removed browser debug-port field.');
assert.match(renderer, /runtimeViewState\s*=\s*window\.RuntimeViewState\.fromSnapshot/u);
assert.match(renderer, /agentRunning\s*=\s*runtimeViewState\.agent\.running/u);
assert.match(renderer, /runtimeStarted=runtimeViewState\.runtime\.active === true/u, 'Start and Stop Runtime must use the runtime lifecycle state.');
assert.match(renderer, /runtimeRestart/u);
assert.match(renderer, /runtimeStop/u);
assert.doesNotMatch(renderer, /browserLoop|checkBrowser|listPages|capturePage/u);
assert.match(renderer, /access-runtime-view-state/u);
assert.match(renderer, /Start Relay to use the only page, or choose one once to remember it/u);
assert.doesNotMatch(html, /agent-workflow-view\.(css|js)/u, 'The unwired duplicate Agent view must not replace the live workbench controls.');

const handlers = [...main.matchAll(/ipcMain\.handle\(\s*['"]([^'"]+)['"]/g)].map(match => match[1]);
assert.equal(new Set(handlers).size, handlers.length, 'IPC handlers must remain unique');
console.log('Runtime controls UI smoke PASS');
